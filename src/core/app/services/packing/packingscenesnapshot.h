#ifndef PACKINGSCENESNAPSHOT_H__
#define PACKINGSCENESNAPSHOT_H__

#include <cstddef>
#include <string>
#include <vector>

////////////////////////////////////////////////////////////////////////////////
//
/// Клетка объекта в снимке сцены упаковки
/**
*/
////////////////////////////////////////////////////////////////////////////////
struct PackingSceneCell
{
  int column = 0;
  int row = 0;
};

////////////////////////////////////////////////////////////////////////////////
//
/// Объект сцены упаковки в локальных координатах
/**
*/
////////////////////////////////////////////////////////////////////////////////
struct PackingSceneObject
{
  std::string id;
  std::vector<PackingSceneCell> cells;
};

////////////////////////////////////////////////////////////////////////////////
//
/// Действие размещения объекта на сцене упаковки
/**
*/
////////////////////////////////////////////////////////////////////////////////
struct PackingSceneAction
{
  std::string type = "place";
  std::string objectId;
  double x = 0.0;
  double y = 0.0;
  double rotationDegrees = 0.0;
};

////////////////////////////////////////////////////////////////////////////////
//
/// Размер доски в снимке сцены упаковки
/**
*/
////////////////////////////////////////////////////////////////////////////////
struct PackingSceneBoard
{
  size_t columns = 0;
  size_t rows = 0;
  std::string unit = "cell";
};

////////////////////////////////////////////////////////////////////////////////
//
/// Снимок результата упаковки для сохранения и будущего воспроизведения
/**
*/
////////////////////////////////////////////////////////////////////////////////
struct PackingSceneSnapshot
{
  PackingSceneBoard board;
  std::vector<PackingSceneObject> objects;
  std::vector<PackingSceneAction> actions;
};

#endif

#ifndef EVENT_H__
#define EVENT_H__

////////////////////////////////////////////////////////////////////////////////
//
/// Тип событий
/**
*/
////////////////////////////////////////////////////////////////////////////////
enum class EventType
{
  MousePress,
  MouseMove,
  MouseRelease,
  Wheel,
  Undo,
  Redo,
  OpenScene,
  Load,
  Save,
  ChangeState,
  Paint,
  Action
};


////////////////////////////////////////////////////////////////////////////////
//
/// Базовый класс события
/**
*/
////////////////////////////////////////////////////////////////////////////////
class Event
{
public:
  // Тип ивента
  virtual EventType type() const = 0;
};

#endif
